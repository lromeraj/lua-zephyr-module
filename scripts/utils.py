def check_executables( executables=[] ):
  for exe in executables:
    if not shutil.which( exe ):
        log.die( "'%s' is not accessible from $PATH" % exe )

def setup(force_build=False):

  if not os.path.exists( LUA_EXE_PATH ) \
      or not os.path.exists( LUAC_EXE_PATH ) or force_build:

    check_executables([ "make" ])

    if not force_build:
      log.wrn( "This build is a one-time process, don't worry" )

    #oldCwd = os.getcwd()
    #os.chdir( LUA_LIB_PATH )

    process = subprocess.run([ "make" ], cwd=LUA_LIB_PATH)

    if process.returncode == 0:
      log.inf( "Build successful" )
    else:
      log.die( "Build failed, please check make output" )
    
    #os.chdir( oldCwd )

  os.environ["PATH"] = os.path.dirname( LUA_EXE_PATH ) \
    + os.pathsep + os.environ["PATH"]